#!/usr/bin/env node
// Builds router/config.yaml, the Mihomo config the NAS side router runs (see
// router/README.md). It is override.js applied to a profile whose only nodes
// come from the airport subscription as a proxy-provider, plus what a LAN
// gateway needs: TUN, a DNS server, the sniffer and a LAN controller. The
// routing is therefore exactly what FlClash devices get.
//
// <SUBSCRIPTION_URL>, <CONTROLLER_SECRET> and <UPSTREAM_DNS> are filled in on
// the NAS when the container starts; the repository never holds real values.
//
//   node tools/build-router-config.mjs           write router/config.yaml
//   node tools/build-router-config.mjs --check   fail if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import { runInNode, scriptValue } from '../test/support/flclash-runtime.mjs';

const repositoryDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const routerConfigPath = path.join(repositoryDirectory, 'router/config.yaml');

export const PLACEHOLDERS = ['<SUBSCRIPTION_URL>', '<CONTROLLER_SECRET>', '<UPSTREAM_DNS>'];

export const ROUTER_BASE = {
  mode: 'rule',
  'log-level': 'warning',
  ipv6: false,
  'unified-delay': true,
  'tcp-concurrent': true,
  'find-process-mode': 'off',
  // Dashboard and API for the LAN: pin a node, switch to Global or Direct.
  // Never forward this port on the router.
  'external-controller': '0.0.0.0:9090',
  secret: '<CONTROLLER_SECRET>',
  'external-ui': 'ui',
  'external-ui-url': 'https://github.com/MetaCubeX/metacubexd/archive/refs/heads/gh-pages.zip',
  // Keeps a node pinned in the dashboard across restarts. The outbound mode is
  // not kept: every start uses `mode` above.
  profile: { 'store-selected': true },
  // LAN devices use this container as their gateway; the TUN takes the
  // traffic they send through it.
  tun: {
    enable: true,
    stack: 'mixed',
    'auto-route': true,
    'auto-detect-interface': true,
    'dns-hijack': ['any:53', 'tcp://any:53'],
  },
  // LAN devices also use it as their DNS server. Answers are real addresses
  // from the LAN router's DNS; Mihomo remembers which name each address came
  // from, so the domain rules still match.
  dns: {
    enable: true,
    listen: '0.0.0.0:53',
    ipv6: false,
    'enhanced-mode': 'redir-host',
    'default-nameserver': ['<UPSTREAM_DNS>'],
    nameserver: ['<UPSTREAM_DNS>'],
  },
  // Recovers the domain of connections made to a bare address, as the Mihomo
  // wiki's example does.
  sniffer: {
    enable: true,
    'force-dns-mapping': true,
    'parse-pure-ip': true,
    'override-destination': true,
    sniff: {
      HTTP: { ports: [80, '8080-8880'], 'override-destination': true },
      TLS: { ports: [443, 8443] },
      QUIC: { ports: [443, 8443] },
    },
    'skip-domain': ['Mijia Cloud', '+.push.apple.com'],
  },
  'proxy-providers': {
    airport: {
      type: 'http',
      url: '<SUBSCRIPTION_URL>',
      // FlClash's default subscription update interval.
      interval: 86400,
      path: './providers/airport.yaml',
      // Only nodes named as mainland exits, as override.js picks inline ones:
      // a subscription may sell overseas nodes too, and the script cannot see
      // a provider's names. An airport whose names carry none of these marks
      // needs its own pattern here.
      filter: scriptValue('MAINLAND_NODE.source'),
    },
  },
};

const HEADER = [
  'Generated by tools/build-router-config.mjs from override.js. Do not edit;',
  'run `node tools/build-router-config.mjs` instead.',
  'The NAS fills in the <...> placeholders at container start (router/compose.yaml).',
];

export function buildRouterConfig() {
  const { output } = runInNode(ROUTER_BASE);
  const document = new YAML.Document(output);
  // Single quotes: the NAS escapes values for this style before filling them in.
  YAML.visit(document, {
    Scalar(_, node) {
      if (typeof node.value === 'string' && PLACEHOLDERS.some((placeholder) => node.value.includes(placeholder))) {
        node.type = 'QUOTE_SINGLE';
      }
    },
  });
  document.commentBefore = HEADER.map((line) => ` ${line}`).join('\n');
  return document.toString({ lineWidth: 0 });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  const text = buildRouterConfig();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(routerConfigPath) ? fs.readFileSync(routerConfigPath, 'utf8') : '';
    if (current !== text) {
      console.error('router/config.yaml is out of date: run node tools/build-router-config.mjs');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(routerConfigPath, text);
  }
}
